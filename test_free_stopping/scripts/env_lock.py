"""Environment lock (PLAN.md §6 Phase 2, DESIGN.md §12 item 6).

Writes the exact software and hardware stack of the machine it runs on: the fields that
can change floating-point results (torch, CUDA, cuDNN, GPU, driver), the CPU, the git
commit, and every installed package with its version. Phase 2a records it on Molab; the
user commits it as configs/env_lock.txt. Later notebooks compare the live environment
against it (`mismatches`) and refuse to train or replay corpus runs on a different stack.

Usage: python -m scripts.env_lock [--device cuda] [--out configs/env_lock.txt]
       python -m scripts.env_lock --check configs/env_lock.txt
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import datetime, timezone
from importlib import metadata
from pathlib import Path

from tfs import cpu_env

PROJECT_ROOT = Path(__file__).resolve().parents[1]
# Header fields compared by `mismatches`. A change in any of them can change results.
KEY_FIELDS = ("torch", "cuda", "cudnn", "gpu", "driver", "python", "numpy")


def key_fields(device: str) -> dict:
    from tfs.training.determinism import EnvRecord

    env = EnvRecord.capture(device)
    return {"torch": env.torch, "cuda": env.cuda, "cudnn": env.cudnn, "gpu": env.gpu, "driver": env.driver,
            "python": env.python, "numpy": env.numpy, "platform": env.platform,
            "cpu_model": cpu_env.cpu_model(), "available_cpus": cpu_env.available_cpus()}


def lock_text(device: str) -> str:
    from tfs.training.determinism import code_version

    fields = key_fields(device)
    code = code_version(PROJECT_ROOT)
    lines = ["# Pinned environment for the corpus (PLAN.md §4.1). Generated by scripts/env_lock.py.",
             f"# written: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
             f"git_commit: {code['commit']}{' (dirty)' if code['dirty'] else ''}"]
    lines += [f"{k}: {v}" for k, v in fields.items()]
    smi = _nvidia_smi()
    if smi:
        lines += ["", "# nvidia-smi"] + [f"#   {s}" for s in smi.splitlines()]
    lines += ["", "# packages"]
    pkgs = {(d.metadata["Name"] or "").lower(): d.version for d in metadata.distributions()}
    lines += [f"{n}=={v}" for n, v in sorted(pkgs.items()) if n]
    return "\n".join(lines) + "\n"


def parse_key_fields(text: str) -> dict:
    out = {}
    for line in text.splitlines():
        if line.startswith("#") or ":" not in line or "==" in line:
            continue
        k, v = line.split(":", 1)
        out[k.strip()] = v.strip()
    return out


def mismatches(lock: str, current: str) -> list[str]:
    """Key fields that differ between two lock texts, as 'field: locked -> current'."""
    a, b = parse_key_fields(lock), parse_key_fields(current)
    return [f"{k}: {a.get(k)} -> {b.get(k)}" for k in KEY_FIELDS if a.get(k) != b.get(k)]


def _nvidia_smi() -> str:
    try:
        r = subprocess.run(["nvidia-smi"], capture_output=True, text=True, timeout=20)
        return r.stdout.strip() if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--out", default=None)
    ap.add_argument("--check", default=None, help="compare the live environment with this lock file")
    args = ap.parse_args()
    text = lock_text(args.device)
    if args.check:
        bad = mismatches(Path(args.check).read_text(), text)
        print("environment matches the lock" if not bad else "MISMATCH:\n  " + "\n  ".join(bad))
        sys.exit(1 if bad else 0)
    if args.out:
        Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
